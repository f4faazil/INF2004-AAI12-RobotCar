#!/usr/bin/env python3
"""Measure the bar/space widths of the lecturer's Code 39 barcode PDFs.

Writes barcode_fixtures.h: one 29-element run-length array per barcode page
(bar, space, bar, ... , bar), in pixels of a 4x raster.  This script does not
decode anything; the expected character is taken from the page's own label
(or, for the unlabelled ActiveBarcode pages, from the letter noted below), so
the C decoder is checked against data it did not produce.

Usage: extract_fixtures.py <path to BARCODE.pdf> > barcode_fixtures.h
Needs PyMuPDF (pip install pymupdf).
"""
import sys
import fitz
import numpy as np

# (page number in BARCODE.pdf, expected character, scale name)
PAGES = [
    (2, 'A', 'large'), (3, 'A', 'medium'), (4, 'A', 'small'),
    (6, 'F', 'large'), (7, 'F', 'medium'), (8, 'F', 'small'),
    (10, 'Z', 'large'), (11, 'Z', 'medium'), (12, 'Z', 'small'),
    (13, 'W', 'large'), (14, 'X', 'medium'), (15, 'Y', 'small'),
]
ROW = 172            # a raster row that crosses every bar, clear of the label
RASTER = 4
ELEMENTS = 29        # 3 characters x 9 elements + 2 inter-character gaps


def runs_at_row(page):
    pix = page.get_pixmap(matrix=fitz.Matrix(RASTER, RASTER), colorspace=fitz.csGRAY)
    row = np.frombuffer(pix.samples, dtype=np.uint8).reshape(pix.height, pix.width)[ROW] < 128
    runs, cur, n = [], bool(row[0]), 1
    for v in row[1:]:
        if bool(v) == cur:
            n += 1
        else:
            runs.append((cur, n))
            cur, n = bool(v), 1
    runs.append((cur, n))
    while runs and not runs[0][0]:
        runs.pop(0)
    while runs and not runs[-1][0]:
        runs.pop()
    return [n for _, n in runs]


def main():
    doc = fitz.open(sys.argv[1])
    print('/* Generated by extract_fixtures.py from the lecturer\'s BARCODE.pdf. */')
    print('/* Widths are in pixels of a 4x raster; bar, space, bar, ..., bar.     */')
    print('#ifndef BARCODE_FIXTURES_H')
    print('#define BARCODE_FIXTURES_H')
    print('#include <stdint.h>')
    print('typedef struct { char expected; const char *scale; uint16_t runs[%d]; } barcode_fixture_t;' % ELEMENTS)
    print('static const barcode_fixture_t BARCODE_FIXTURES[] = {')
    for page, ch, scale in PAGES:
        w = runs_at_row(doc[page - 1])
        assert len(w) == ELEMENTS, (page, len(w))
        print("    { '%s', \"%s\", { %s } }," % (ch, scale, ', '.join(str(x) for x in w)))
    print('};')
    print('#define BARCODE_FIXTURE_COUNT (sizeof(BARCODE_FIXTURES) / sizeof(BARCODE_FIXTURES[0]))')
    print('#endif')


main()
